#!/usr/bin/env node
/**
 * Generate the typed Manufact Cloud client from a Cloud OpenAPI document.
 *
 *   pnpm --filter @mcp-use/cli generate:cloud-client <openapi.json>
 *
 * The OpenAPI document is an input only and is not committed.
 *
 * Writes:
 * - `src/cloud/api/generated/`: the @hey-api/openapi-ts client, restricted to
 *   the operations the CLI uses. SDK functions are flat so the bundler drops
 *   the ones a command does not call.
 * - `tests/helpers/cloud-routes.gen.ts`: the same operations keyed by
 *   `METHOD /path`, with each one's documented success status, which types
 *   the fake Cloud in the test harness.
 *
 * Both outputs are committed. Never edit them by hand; change the scope below
 * and regenerate.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { createClient } from "@hey-api/openapi-ts";

const PACKAGE_DIR = fileURLToPath(new URL("../", import.meta.url));
const input = process.argv[2];
if (input === undefined) {
  console.error(
    "Usage: pnpm --filter @mcp-use/cli generate:cloud-client <openapi.json>"
  );
  process.exit(2);
}
const SNAPSHOT = resolve(process.cwd(), input);
const OUTPUT = `${PACKAGE_DIR}src/cloud/api/generated`;
const ROUTES = `${PACKAGE_DIR}tests/helpers/cloud-routes.gen.ts`;

/**
 * The exact operations the CLI calls, as `METHOD /path`. Add an operation
 * here in the same change as the command that calls it, and check the
 * regenerated types before committing them.
 */
const OPERATIONS = [
  "GET /api/v1/deployments",
  "POST /api/v1/deployments",
  "GET /api/v1/deployments/{id}",
  "GET /api/v1/deployments/{id}/build-logs",
  "GET /api/v1/deployments/{id}/logs",
];

const spec = JSON.parse(await readFile(SNAPSHOT, "utf8"));
const operations = OPERATIONS.map((key) => {
  const space = key.indexOf(" ");
  const method = key.slice(0, space).toLowerCase();
  const path = key.slice(space + 1);
  const operation = spec.paths[path]?.[method];
  if (operation === undefined) {
    throw new Error(`The OpenAPI document has no ${key}.`);
  }
  if (typeof operation.operationId !== "string") {
    throw new Error(`${key} has no operationId.`);
  }
  const successStatuses = Object.keys(operation.responses ?? {})
    .map(Number)
    .filter((status) => status >= 200 && status < 300)
    .sort((a, b) => a - b);
  return {
    key,
    operationId: operation.operationId,
    successStatus: successStatuses[0] ?? 200,
  };
});
operations.sort((a, b) => a.key.localeCompare(b.key));

await createClient({
  input: SNAPSHOT,
  output: { path: OUTPUT, clean: true, indexFile: false },
  logs: { level: "warn" },
  parser: {
    filters: {
      operations: { include: operations.map((operation) => operation.key) },
    },
  },
  plugins: [
    "@hey-api/typescript",
    { name: "@hey-api/client-fetch", baseUrl: "https://cloud.manufact.com" },
    { name: "@hey-api/sdk", operations: { strategy: "flat" } },
  ],
});

// hey-api's runtime helpers are not written for `exactOptionalPropertyTypes`,
// which this package enables. They are vendored, generated code, so skip
// type-checking them; the operation types and SDK functions stay checked.
for (const folder of ["client", "core"]) {
  for (const name of await readdir(`${OUTPUT}/${folder}`)) {
    const file = `${OUTPUT}/${folder}/${name}`;
    await writeFile(file, `// @ts-nocheck\n${await readFile(file, "utf8")}`);
  }
}

// The route map for the fake Cloud. Every operation must have the types the
// generator emitted for it, or the map would silently fall out of step.
const types = await readFile(`${OUTPUT}/types.gen.ts`, "utf8");
const has = (name) => types.includes(`export type ${name} =`);
const lines = [];
for (const { key, operationId } of operations) {
  const name = operationId[0].toUpperCase() + operationId.slice(1);
  if (!has(`${name}Data`)) {
    throw new Error(`No generated types for ${key} (${name}).`);
  }
  // An operation that documents no success or error status gets an empty map.
  const none = "Record<never, never>";
  const responses = has(`${name}Responses`) ? `T.${name}Responses` : none;
  const errors = has(`${name}Errors`) ? `T.${name}Errors` : none;
  lines.push(
    `  ${JSON.stringify(key)}: {`,
    `    operationId: ${JSON.stringify(operationId)};`,
    `    data: T.${name}Data;`,
    `    responses: ${responses};`,
    `    errors: ${errors};`,
    `  };`
  );
}
await writeFile(
  ROUTES,
  [
    "// Generated by scripts/generate-cloud-client.mjs. Do not edit.",
    "//",
    "// Every Cloud operation the CLI's generated client covers, keyed by",
    "// `METHOD /path` as written in the Cloud OpenAPI document.",
    'import type * as T from "../../src/cloud/api/generated/types.gen.js";',
    "",
    "export interface CloudRoutes {",
    ...lines,
    "}",
    "",
    "/** The keys of {@link CloudRoutes}, for matching requests at runtime. */",
    "export const cloudRouteKeys: readonly (keyof CloudRoutes)[] = [",
    ...operations.map(({ key }) => `  ${JSON.stringify(key)},`),
    "];",
    "",
    "/** The status each route answers with when a reply sets none. */",
    "export const cloudRouteSuccessStatus: Readonly<",
    "  Record<keyof CloudRoutes, number>",
    "> = {",
    ...operations.map(
      ({ key, successStatus }) => `  ${JSON.stringify(key)}: ${successStatus},`
    ),
    "};",
    "",
  ].join("\n")
);

console.log(
  `Generated ${operations.length} Cloud operations into src/cloud/api/generated.`
);
