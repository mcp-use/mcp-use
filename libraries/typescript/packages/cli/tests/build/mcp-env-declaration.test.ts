import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { syncMcpEnvDeclaration } from "../../src/toolchain/mcp-env-declaration.js";

const tempDirs: string[] = [];

afterEach(async () => {
  await Promise.all(
    tempDirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true }))
  );
});

describe("syncMcpEnvDeclaration", () => {
  it.each([
    ["index.ts", "./index.js"],
    ["src/index.tsx", "./src/index.js"],
    ["src/index.mts", "./src/index.mjs"],
    ["src/index.cts", "./src/index.cjs"],
    ["server.mjs", "./server.mjs"],
  ])("writes %s as the runtime import %s", async (entry, expected) => {
    const cwd = await mkdtemp(join(tmpdir(), "mcp-use-env-"));
    tempDirs.push(cwd);

    await expect(syncMcpEnvDeclaration(cwd, join(cwd, entry))).resolves.toBe(
      "created"
    );

    await expect(
      readFile(join(cwd, "mcp-env.d.ts"), "utf8")
    ).resolves.toContain(`tools: typeof import(${JSON.stringify(expected)})`);
  });

  it("refreshes a declaration generated by an earlier mcp-use version", async () => {
    const cwd = await mkdtemp(join(tmpdir(), "mcp-use-env-"));
    tempDirs.push(cwd);
    const declaration = join(cwd, "mcp-env.d.ts");
    await writeFile(
      declaration,
      "// mcp-use generated env declaration\nlegacy\n"
    );

    await expect(
      syncMcpEnvDeclaration(cwd, join(cwd, "server.ts"))
    ).resolves.toBe("updated");
    await expect(readFile(declaration, "utf8")).resolves.toContain(
      'tools: typeof import("./server.js")'
    );
  });
});
